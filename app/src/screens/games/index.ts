export type GameId = keyof typeof GAME_REGISTRY;

/**
 * Get game metadata by ID
 */
export function getGameMetadata(gameId: string) {
  return GAME_REGISTRY[gameId as GameId] || null;
}

/**
 * Get all games in a category
 */
export function getGamesByCategory(categoryId: string) {
  return Object.entries(GAME_REGISTRY)
    .filter(([, metadata]) => metadata.category === categoryId)
    .map(([id, metadata]) => ({ id, ...metadata }));
}

